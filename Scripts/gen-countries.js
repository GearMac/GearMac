#!/usr/bin/env node
// 文件职责：生成 GearMac/Features/Calculator/Model/CountryZoneData.generated.swift，即「国家 → 主时区」查询表。
// 分层：脚本（代码生成器）；产物是 generated 文件，只能由本脚本生成，禁止手改。
//
// 用法：node Scripts/gen-countries.js [zone.tab cldr-territories.json]
// 未给出路径时从网络下载数据源。偶尔跑一次，并把输出一并提交。
//
// 两个数据源，按 ISO 3166 国家代码关联：
//   - IANA 的 zone.tab 决定一个国家用*哪个*时钟报时。它列出每个国家的全部时区，在地理条件允许时按人口
//     从多到少排列，所以它的第一行就是该国的主时钟。Foundation 自带时区本身，但没有「时区属于哪个国家」的概念。
//   - CLDR 的 `en` 地区名决定人们对这个国家的*称呼*，包含短名（"UK"、"US"）。数据取自 cldr-json 而不是
//     宿主机的 `Intl`，后者的输出会随 ICU 版本变化。
//
// 两个国家共用的拼写会被剔除，而不是猜测归属。
"use strict";

const fs = require("fs");
const path = require("path");

const ZONE_TAB = "https://data.iana.org/time-zones/tzdb/zone.tab";
const CLDR_TERRITORIES =
  "https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-localenames-full/main/en/territories.json";

// zone.tab 先按地理、后按人口排序，这会把这些国家的边远时区排在最前。
// 这些国家改为用首都的时钟报时；一旦某个首都不再被列出，脚本会直接报错。
const CAPITAL_ZONES = {
  AU: "Australia/Sydney",
  BR: "America/Sao_Paulo",
  CA: "America/Toronto",
  FM: "Pacific/Pohnpei",
  RU: "Europe/Moscow",
  UA: "Europe/Kyiv",
  UZ: "Asia/Tashkent",
};
// 这些领地没有首都，且辖内时钟相差半个地球，根本给不出单一时间。
const NO_SINGLE_CLOCK = new Set(["AQ", "UM"]);

// zone.tab 大约列出 250 个代码；明显低于这个数量说明响应异常。
const MIN_EXPECTED = 230;

/// 读取本地文件；没有传入路径时从 url 下载文本。
async function loadText(url, argPath) {
  if (argPath) return fs.readFileSync(argPath, "utf8");
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} -> HTTP ${response.status}`);
  return response.text();
}

/// 一个名字的所有可查询形式：像查询那样做折叠并转小写，再加上键盘为 CLDR 的排版字符
/// `&` 和 `’` 实际会敲出的写法。
function spellings(name) {
  const base = name
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/\s+/g, " ")
    .trim();
  const forms = new Set([base, base.replace(/’/g, "'")]);
  for (const form of [...forms]) if (form.includes(" & ")) forms.add(form.replace(/ & /g, " and "));
  return forms;
}

/// 把 code 记为 key 名下的一名主张者，供后续剔除多国共用的拼写。
function claim(map, key, code) {
  if (!map.has(key)) map.set(key, new Set());
  map.get(key).add(code);
}

/// 把值包成 Swift 字符串字面量；含会引起转义歧义的字符时直接报错。
function swiftString(value) {
  if (value.includes('"') || value.includes("\\")) throw new Error(`unsafe literal ${JSON.stringify(value)}`);
  return `"${value}"`;
}

/// 国家代码 → 时区列表，顺序沿用 zone.tab 自身的顺序。
function zonesByCountry(text) {
  const zones = new Map();
  for (const line of text.split("\n")) {
    if (!line || line.startsWith("#")) continue;
    const [code, , zone] = line.split("\t");
    if (!/^[A-Z]{2}$/.test(code) || !zone) throw new Error(`unexpected zone.tab row: ${line}`);
    if (!zones.has(code)) zones.set(code, []);
    zones.get(code).push(zone);
  }
  return zones;
}

/// 取该国的主时钟：先看 CAPITAL_ZONES 指定的首都时区，否则用 zone.tab 的第一行。
function mainClock(code, zones) {
  const capital = CAPITAL_ZONES[code];
  if (!capital) return zones[0];
  if (!zones.includes(capital)) throw new Error(`${capital} is no longer listed for ${code}`);
  return capital;
}

/// 拉取两个数据源，生成「国家 → 主时区」表并写入 generated 文件。
async function main() {
  const zones = zonesByCountry(await loadText(ZONE_TAB, process.argv[2]));
  const cldr = JSON.parse(await loadText(CLDR_TERRITORIES, process.argv[3]));
  const names = cldr?.main?.en?.localeDisplayNames?.territories;
  if (!names) throw new Error("unexpected CLDR shape: main.en.localeDisplayNames.territories missing");
  if (zones.size < MIN_EXPECTED) throw new Error(`suspiciously few countries: ${zones.size}`);

  const claims = new Map();
  const unnamed = [];
  for (const [code, list] of zones) {
    if (NO_SINGLE_CLOCK.has(code)) continue;
    // `GB`、`GB-alt-short` 与 `GB-alt-variant` 都是同一个国家的名字。
    const keys = Object.keys(names).filter((key) => key === code || key.startsWith(`${code}-alt-`));
    if (keys.length === 0) unnamed.push(code);
    const zone = mainClock(code, list);
    for (const key of keys) for (const form of spellings(names[key])) claim(claims, form, zone);
  }

  const table = [...claims]
    .filter(([, owners]) => owners.size === 1)
    .map(([name, owners]) => [name, [...owners][0]])
    .sort((a, b) => a[0].localeCompare(b[0]));
  const contested = claims.size - table.length;

  const out = path.resolve(
    __dirname,
    "..",
    "GearMac/Features/Calculator/Model/CountryZoneData.generated.swift",
  );
  fs.writeFileSync(
    out,
    "// Generated by Scripts/gen-countries.js — do not edit by hand.\n" +
      "// Clocks from IANA zone.tab; country names from Unicode CLDR (en).\n" +
      "enum CountryZoneData {\n" +
      "    /// Folded, lowercased country name → the IANA zone of its main clock.\n" +
      "    static let zones: [String: String] = [\n" +
      table.map(([name, zone]) => `        ${swiftString(name)}: ${swiftString(zone)},`).join("\n") +
      "\n    ]\n" +
      "}\n",
  );
  console.log(
    `wrote ${out} — ${table.length} names for ${zones.size - NO_SINGLE_CLOCK.size} countries ` +
      `(${contested} contested, unnamed: ${unnamed.join(", ") || "none"})`,
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
